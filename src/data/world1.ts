import type { Level, LevelKind, Phrase, World } from './types';

type Raw = [en: string, es: string, tip: string, traps?: string[]];

function level(
  n: number,
  kind: LevelKind,
  character: string,
  title: string,
  story: string,
  goal: string,
  raw: Raw[],
  boss?: Level['boss'],
): Level {
  const id = `w1-${n}`;
  const phrases: Phrase[] = raw.map(([en, es, tip, traps], i) => ({
    id: `${id}-${i + 1}`,
    en,
    es,
    tip,
    traps,
  }));
  return { id, n, kind, character, title, story, goal, phrases, boss };
}

